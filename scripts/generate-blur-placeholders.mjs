import sharp from "sharp";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const publicDir = path.join(__dirname, "..", "public");

const images = [
  { id: "logoTexto", path: "assets/brand/logo-texto.webp" },
  { id: "midnightCinematic", path: "assets/images/midnight-cinematic.webp" },
  { id: "midnightBattle", path: "assets/images/midnight-battle.webp" },
  { id: "historiaCultura", path: "assets/images/historia-cultura.webp" },
  { id: "recruitment", path: "assets/images/recruitment.webp" },
];

async function generateBlurDataURL(imagePath) {
  const buffer = await sharp(imagePath)
    .resize(10)
    .webp({ quality: 20 })
    .toBuffer();
  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

async function main() {
  const entries = [];

  for (const { id, path: relativePath } of images) {
    const fullPath = path.join(publicDir, relativePath);
    if (!fs.existsSync(fullPath)) {
      console.warn(`Skipping missing image: ${relativePath}`);
      continue;
    }

    console.log(`Generating blur placeholder for ${relativePath}...`);
    try {
      const dataUrl = await generateBlurDataURL(fullPath);
      entries.push({ id, dataUrl });
      console.log(`  -> ${dataUrl.length} chars`);
    } catch (err) {
      console.error(`Failed to generate placeholder for ${relativePath}:`, err);
    }
  }

  const output = `// Auto-generated by scripts/generate-blur-placeholders.mjs
// Do not edit manually. Run prebuild to regenerate.

export const blurDataUrls = {
${entries.map(({ id, dataUrl }) => `  ${id}: "${dataUrl}",`).join("\n")}
} as const;
`;

  const outputDir = path.join(__dirname, "..", "src", "shared", "images");
  fs.mkdirSync(outputDir, { recursive: true });
  const outputPath = path.join(outputDir, "blur-data-urls.ts");
  fs.writeFileSync(outputPath, output, "utf-8");
  console.log(`\nGenerated ${outputPath} with ${entries.length} blur placeholders.`);
}

main().catch((err) => {
  console.error("Error generating blur placeholders:", err);
  process.exit(1);
});
